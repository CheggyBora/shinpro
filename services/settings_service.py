class SettingsService:
    def __init__(self, db):
        self.db = db

    def get(self, key, default=None):
        """Значение настройки строкой."""
        setting = self.db.query(Settings).filter(Settings.key == key).first()
        if setting and setting.value is not None:
            return setting.value
        if default is not None:
            return default
        return DEFAULTS.get(key)

    def get_raw(self, key):
        """
        Значение как оно есть в базе, без подмены на значение по умолчанию.

        Нужно там, где пустая строка — осмысленный ответ («не печатать это
        поле»), а не «настройку ещё не заводили». Возвращает None, если
        настройки в базе нет.
        """
        setting = self.db.query(Settings).filter(Settings.key == key).first()
        return setting.value if setting else None

    def get_int(self, key, default=None):
        try:
            return int(float(self.get(key, default)))
        except (TypeError, ValueError):
            fallback = default if default is not None else DEFAULTS.get(key, 0)
            return int(float(fallback))

    def get_float(self, key, default=None):
        try:
            return float(self.get(key, default))
        except (TypeError, ValueError):
            fallback = default if default is not None else DEFAULTS.get(key, 0)
            return float(fallback)

    def set(self, key, value, commit=True):
        setting = self.db.query(Settings).filter(Settings.key == key).first()
        if setting:
            if setting.value == str(value):
                # Записать то же самое — значит сдвинуть метку времени
                # и тем самым «выиграть» у дашборда, ничего не поменяв.
                # Окно настроек сохраняет все поля сразу, так что без
                # этой проверки любое сохранение отменяло бы правку
                # владельца, сделанную из дашборда.
                # Но commit всё равно делаем: этим вызовом часто
                # закрывают пачку правок, сделанных с commit=False
                if commit:
                    self.db.commit()
                return
            setting.value = str(value)
            setting.changed_at = get_moscow_time()
        else:
            self.db.add(Settings(key=key, value=str(value),
                                 changed_at=get_moscow_time()))
        if commit:
            self.db.commit()

    # Что считается выключением. Всё остальное — включено, в том числе
    # пустое и непонятное. Выключенный приём записи закрывает точку для
    # клиентов, и приходить к этому из-за сбоя нельзя: выключают
    # осознанно, галочкой здесь или кнопкой в дашборде
    OFF = ('0', 'false', 'no', 'нет', 'выкл')

    def is_on(self, key):
        """Включена ли настройка-выключатель."""
        return str(self.get(key, '')).strip().lower() not in self.OFF

    def changed_at(self, key):
        """Когда настройку поменяли в цеху. None — ни разу с обновления."""
        setting = self.db.query(Settings).filter(Settings.key == key).first()
        return setting.changed_at if setting else None

    def adopt(self, key, value, changed_at, commit=True):
        """
        Принять значение, пришедшее с сервера.

        Метку времени берём серверную, а не ставим «сейчас»: иначе цех
        всегда оказывался бы прав последним, и правка из дашборда
        уезжала бы обратно при следующем же обмене.
        """
        setting = self.db.query(Settings).filter(Settings.key == key).first()
        if setting:
            setting.value = str(value)
            setting.changed_at = changed_at
        else:
            self.db.add(Settings(key=key, value=str(value),
                                 changed_at=changed_at))
        if commit:
            self.db.commit()

    def ensure_defaults(self):
        """Завести отсутствующие настройки со значениями по умолчанию."""
        created = 0
        for key, value in DEFAULTS.items():
            if not self.db.query(Settings).filter(Settings.key == key).first():
                self.db.add(Settings(key=key, value=value))
                created += 1
        if created:
            self.db.commit()
        return created
