"""
Основная услуга или допродажа.

Основное — то, ради чего человек приехал: снять колесо, перебортовать,
отбалансировать, помыть. Всё остальное он не планировал, и оно попало
в чек потому, что мастер предложил: ремонт прокола, правка диска,
хранение, датчик давления.

Деление ни на что не влияет — ни на цену, ни на зарплату. Оно нужно
владельцу, чтобы по доле допов видеть, предлагают мастера что-то сверх
или просто крутят колёса.

**Почему по началу названия, а не по вхождению.** «Оптимизация
балансировки» и «Проверка на балансировку» содержат слово «баланс», но
основными не являются: первое — доплата за точность, второе — проверка.
Совпадение по началу названия отделяет саму услугу от всего, что
вокруг неё.

Правило работает один раз, при обновлении программы. Дальше вид правится
руками в прайс-листе и больше не трогается: владелец знает свой
шиномонтаж лучше любого списка слов.
"""

# С чего начинается название основной услуги. «Съем» и «съём» — оба
# написания: в прайсе встречаются вперемешку
MAIN_PREFIXES = (
    'съем',
    'съём',
    'шиномонтаж',
    'балансировка',
    'мойка',
)


def looks_main(name):
    """Похоже ли название на основную услугу."""
    clean = (name or '').strip().lower()
    return any(clean.startswith(prefix) for prefix in MAIN_PREFIXES)


def looks_extra(name):
    return not looks_main(name)
