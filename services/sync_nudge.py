"""
Срочная досылка: не ждать десяти минут там, где ждать нельзя.

Обмен ходит раз в десять минут, и для большинства данных это нормально:
наверх едут копии, отстать им нечем повредить. Но часть изменений видна
человеку сразу, и десять минут ожидания выглядят поломкой:

  · оплатили наряд — владелец смотрит в дашборд и не видит выручки;
  · машина заехала на пост — клиент смотрит очередь и видит вчерашнее;
  · выключили приём записи — а клиенты ещё десять минут записываются;
  · приняли комплект на хранение — в кабинете его нет.

Поэтому после таких событий цех выходит на связь сам, не дожидаясь
расписания.

**Это не отдельный путь обмена, а тот же самый, запущенный раньше.**
Своего протокола у срочной досылки нет, и данные она отправляет те же.
Иначе пришлось бы держать два способа отправки и следить, чтобы они не
разошлись.

**Нажатие ничего не ждёт.** Досылка откладывается на пару секунд и идёт
в отдельном потоке. Приёмщик, оплативший наряд, не должен смотреть на
замерший экран, пока программа ходит в сеть, — и тем более не должен
получать ошибку сети вместо чека.

**Пачкой, а не по событию.** Приёмщик закрывает наряд, следом второй,
следом двигает машину по постам — это три события за десять секунд.
Отправляем один раз: пока досылка отложена, новые просьбы к ней
присоединяются, а не плодят ещё отправки.

**Не дошло — не беда.** Сеть пропала, сервер не ответил — данные
уедут при ближайшем обмене по расписанию. Поэтому здесь нет ни
повторов, ни очереди: вся надёжность уже есть в обычном обмене, и
дублировать её значит получить два разных поведения.
"""
from logger import log

# Через сколько выходить на связь после события. Пара секунд, чтобы
# подхватить то, что случится следом: приёмщик редко делает одно
# действие и замирает
DELAY_SECONDS = 3

# Кто умеет запускать обмен. Ставит главное окно при запуске: сервисы
# про интерфейс не знают и знать не должны
_runner = None


def set_runner(runner):
    """
    Сказать, чем запускать досылку.

    runner(delay_ms, reason) — главное окно откладывает обмен через
    свой таймер. Отдельный поток с таймером здесь завести нельзя:
    обмен трогает базу, а она у программы одна на всех.
    """
    global _runner
    _runner = runner


def request(reason):
    """
    Попросить выйти на связь, не дожидаясь расписания.

    reason — чем вызвано, одной строкой. Уходит в журнал: когда
    разбираются, почему обмен шёл чаще обычного, это первое, что
    хочется увидеть.

    Ошибки проглатываем молча. Досылка — ускорение, а не обязанность:
    уронить оплату наряда из-за того, что не получилось позвать обмен,
    было бы обменом наоборот.
    """
    if _runner is None:
        return False

    try:
        return bool(_runner(DELAY_SECONDS * 1000, reason))
    except Exception as e:
        log.warning(f"Не удалось позвать срочный обмен ({reason}): {e}")
        return False
